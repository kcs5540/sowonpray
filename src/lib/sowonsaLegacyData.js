// 🏮 [대웅전 1년 인등단 좌석 그리드 생성기 (200석: 동편 A 100석, 서편 B 100석)]
export function generateIndeungSeats(memberList = SOWONSA_INITIAL_MEMBERS) {
  const seats = []
  const sections = [
    { code: '동', name: '동편 인등단 (부처님 좌측)' },
    { code: '서', name: '서편 인등단 (부처님 우측)' },
  ]

  sections.forEach((sec) => {
    // 10단 x 10열 = 100석
    for (let row = 1; row <= 10; row++) {
      for (let col = 1; col <= 10; col++) {
        const num = (row - 1) * 10 + col
        const seatCode = `인등-${sec.code}-${num < 10 ? '0' + num : num}`

        // 신도 기도 내역 중 배정된 자리 찾기
        let assignedMember = null
        let assignedPrayer = null

        for (const m of memberList) {
          const pr = (m.prayers || []).find((p) => p.seat_code === seatCode)
          if (pr) {
            assignedMember = m
            assignedPrayer = pr
            break
          }
        }

        seats.push({
          id: seatCode,
          section: sec.code,
          sectionName: sec.name,
          row,
          col,
          seatNumber: num,
          code: seatCode,
          isOccupied: !!assignedMember,
          memberCode: assignedMember ? assignedMember.code : null,
          memberName: assignedMember ? assignedMember.name : null,
          dharmaName: assignedMember ? assignedMember.dharma_name : null,
          phone: assignedMember ? assignedMember.phone : null,
          prayerCategory: assignedPrayer ? assignedPrayer.category : '대웅전 1년 인등',
          appliedAt: assignedPrayer ? assignedPrayer.applied_at : null,
          status: assignedMember ? 'occupied' : 'vacant', // occupied, vacant, expiring
        })
      }
    }
  })

  return seats
}

// 🪔 [지장전 영구위패단 좌석 그리드 생성기 (160석: 상단 80석, 하단 80석)]
export function generateWipaeSeats(memberList = SOWONSA_INITIAL_MEMBERS) {
  const seats = []
  const tiers = [
    { code: '상', name: '지장전 상단 영구위패단 (1~4단)' },
    { code: '하', name: '지장전 하단 영구위패단 (5~8단)' },
  ]

  tiers.forEach((tier) => {
    // 4단 x 20열 = 80석
    for (let row = 1; row <= 4; row++) {
      for (let col = 1; col <= 20; col++) {
        const num = (row - 1) * 20 + col
        const seatCode = `위패-${tier.code}-${num < 10 ? '0' + num : num}`

        let assignedMember = null
        let assignedYoungga = null
        let assignedPrayer = null

        for (const m of memberList) {
          const yg = (m.younggas || []).find((y) => y.seat_code === seatCode)
          if (yg) {
            assignedMember = m
            assignedYoungga = yg
            assignedPrayer = (m.prayers || []).find((p) => p.seat_code === seatCode)
            break
          }
        }

        seats.push({
          id: seatCode,
          tier: tier.code,
          tierName: tier.name,
          row,
          col,
          seatNumber: num,
          code: seatCode,
          isOccupied: !!assignedYoungga,
          memberCode: assignedMember ? assignedMember.code : null,
          pokwiName: assignedYoungga ? assignedYoungga.pokwi : (assignedMember ? assignedMember.name : null),
          younggaName: assignedYoungga ? assignedYoungga.name : null,
          relation: assignedYoungga ? assignedYoungga.relation : null,
          bonkwan: assignedYoungga ? assignedYoungga.bonkwan : null,
          dharmaName: assignedYoungga ? assignedYoungga.dharma_name : null,
          wipaeType: assignedYoungga ? assignedYoungga.wipae_type : '영구위패',
          deathDate: assignedYoungga ? assignedYoungga.death_date : null,
          status: assignedYoungga ? 'occupied' : 'vacant',
        })
      }
    }
  })

  return seats
}
